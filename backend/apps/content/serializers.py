IMAGE_SRC_HELP = "Resolved image URL (uploaded file if present, otherwise image_url)."


class AutoSlugMixin:
    """Slugs are generated by the model, so the API must not require them."""

    def get_extra_kwargs(self):
        kwargs = super().get_extra_kwargs()
        if (
            "slug" in getattr(self.Meta, "fields", [])
            or getattr(self.Meta, "fields", None) == "__all__"
        ):
            kwargs.setdefault("slug", {"required": False, "allow_blank": True, "allow_null": True})
        return kwargs


class ImageSrcMixin(AutoSlugMixin, serializers.ModelSerializer):
    image_src = serializers.CharField(read_only=True, help_text=IMAGE_SRC_HELP)

    def validate_image(self, value):
        if value:
            validate_image_upload(value)
        return value


