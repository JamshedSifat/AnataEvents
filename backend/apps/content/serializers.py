class ServiceDetailSerializer(ServiceListSerializer):
    entries = serializers.SerializerMethodField()

    class Meta(ServiceListSerializer.Meta):
        fields = [*ServiceListSerializer.Meta.fields, "body", "entries"]

    def get_entries(self, obj) -> list:
        request = self.context.get("request")
        qs = obj.serviceentry_set.all()
        if not (request and getattr(request.user, "is_staff", False)):
            qs = qs.filter(is_published=True)
        qs = qs.order_by("order", "id")
        return ServiceEntryListSerializer(qs, many=True, context=self.context).data


